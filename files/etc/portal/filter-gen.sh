#!/bin/sh
# Generate /etc/portal/proxy-bypass.txt and /etc/sing-box/config.json from:
#   filter-domains.txt — white list: domains (with subdomains) go DIRECT
#   filter-black.txt   — black list: domains forced THROUGH the proxy
#   filter-ips.txt     — direct IP ranges (anti-ECH)
# JSON is generated from config-template.json — never edit config.json by hand.
export PATH=/usr/sbin:/usr/bin:/sbin:/bin
CD=/etc/portal
SRC=$CD/filter-domains.txt
BLK=$CD/filter-black.txt
IPS=$CD/filter-ips.txt
TPL=$CD/config-template.json
CFG=/etc/sing-box/config.json
[ -s "$TPL" ] || { echo "ОШИБКА: нет шаблона $TPL"; exit 1; }
[ -s "$SRC" ] || SRC=/dev/null
[ -s "$BLK" ] || BLK=/dev/null
[ -s "$IPS" ] || IPS=/dev/null

# --- 1) opera-proxy bypass list: *.domain (+ bare domain, just in case) ---
{
  echo "# Generated by filter-gen.sh — правьте /etc/portal/filter-domains.txt"
  sed 's/^\*\+\.\+//' "$SRC" | awk '
    /^[[:space:]]*#/ { print; next }
    NF               { d=$1; sub(/\.$/, "", d); if (d ~ /^[A-Za-z0-9._-]+$/) { print "*." d; print d } }
  '
} > $CD/proxy-bypass.txt.new

# --- 2) sing-box config.json from template ---
norm() { grep -v '^[[:space:]]*#' "$1" 2>/dev/null | sed 's/^\*\+\.//' | awk 'NF{ sub(/\.$/, "", $1); print $1 }' | sort -u | grep -E '^[A-Za-z0-9._-]+$' | awk '
  BEGIN{ORS=""} { printf "%s\"%s\"", (n++?",":""), $0 }'; }
ds=$(norm "$SRC")
black=$(norm "$BLK")
ipc=$(grep -v '^[[:space:]]*#' "$IPS" 2>/dev/null | grep -E '^[0-9a-fA-F:./]+$' | sort -u | awk '
  BEGIN{ORS=""} { printf "%s\"%s\"", (n++?",":""), $0 }')
[ -n "$ipc" ] || ipc='"127.0.0.0/8"'

# full-VPN devices: all their traffic forced through opera (white/black ignored)
fullips=$(awk 'NF' $CD/dev-full.txt 2>/dev/null | grep -E '^[0-9]{1,3}(\.[0-9]{1,3}){3}$' | sort -u | awk '
  BEGIN{ORS=""} { printf "%s\"%s\"", (n++?",":""), $0 }')
if [ -n "$fullips" ]; then
  fullrule=$(printf '      { "inbound": [ "tun-in" ], "source_ip_cidr": [%s], "outbound": "opera" },' "$fullips")
else
  fullrule=
fi

if [ -n "$black" ]; then
  brule=$(printf '      { "inbound": [ "tun-in" ], "domain_suffix": [%s], "outbound": "opera" },' "$black")
else
  brule=
fi

# empty list -> 0, not 1 (echo "" | wc -l would report one empty element)
cnt() { if [ -n "$1" ]; then printf '%s\n' "$1" | tr ',' '\n' | grep -c .; else echo 0; fi; }

sed -e "s|__DOMAIN_SUFFIX__|$ds|" -e "s|__IP_CIDR__|$ipc|" -e "s|__BLACK_RULE__|$brule|" -e "s|__FULL_RULE__|$fullrule|" "$TPL" > $CFG.new
if sing-box check -c $CFG.new >/dev/null 2>&1; then
  # publish both files only after the config passed the check, so a broken list
  # never leaves a mismatched proxy-bypass.txt (opera-proxy would go direct wrongly)
  mv $CFG.new $CFG
  mv $CD/proxy-bypass.txt.new $CD/proxy-bypass.txt
  nd=$(cnt "$ds")
  nb=$(cnt "$black")
  ni=$(cnt "$ipc")
  nf=$(cnt "$fullips")
  echo "OK: белый=$nd доменов (напрямую), чёрный=$nb (форс через прокси), $ni IP-блоков, полный=$nf устройств"
else
  rm -f $CFG.new $CD/proxy-bypass.txt.new
  echo "ОШИБКА: конфиг не прошёл проверку sing-box check — старый конфиг сохранён"
  exit 1
fi
